"""Style template families: "Old Realm" and retro game eras.

* ``old-realm-*``: in the spirit of late-1990s online fantasy RPG soundtracks
  (General MIDI, renaissance/medieval colour, modal harmony, long gentle loops).
* ``retro-*``: classic console and home-computer game eras (8-bit chip channels,
  16-bit JRPG and action soundtracks, early PC FM-synth adventures).

Like every template these describe *genre traits* only (ensemble, registers,
tempo, form, chord plans, playing patterns). They contain no melodies and must
not be used to recreate music from any specific game: the agent writes
original material.
"""

